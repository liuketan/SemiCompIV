## Manuscript simulation tables (LaTeX) and the B12 figure, written to output/.
## Run after run_manifest.sh, run_bootstrap.R, compute_poplimits.R and
## aggregate_results.R.
dir.create("output", showWarnings = FALSE)
P <- read.csv("performance_summary.csv", stringsAsFactors = FALSE)
L <- read.csv("population_limits_rho50.csv", stringsAsFactors = FALSE)
fmt <- function(x, d = 3) ifelse(is.na(x), "--", formatC(x, format = "f", digits = d))

## bootstrap check: influence-function vs refitted-bootstrap standard errors
S7 <- readRDS("scenario_S7_boot_rho50_n1000.rds"); M <- S7$M
B <- do.call(rbind, lapply(1:3, function(j) {
  e <- M[, paste0("B12", j)]; tr <- 0.12 * c(.5, 1, 1.5)[j]
  se <- M[, paste0("se12", j)]; bs <- M[, paste0("bse12", j)]
  data.frame(coord = paste0("B12", j), truth = tr, bias = mean(e) - tr, ESE = sd(e),
             IF_ASE = mean(se), Boot_ASE = mean(bs, na.rm = TRUE),
             CP_IF = mean(abs(e - tr) <= 1.96 * se),
             CP_Boot = mean(abs(e - tr) <= 1.96 * bs, na.rm = TRUE), valid = nrow(M))
}))
write.csv(B, "bootstrap_summary.csv", row.names = FALSE)

tex <- c("% Auto-generated by make_tables_figures.R",
 "\\begin{table}[htbp]", "\\centering", "\\caption{Identification-valid designs (2,000 replicates).}", "\\label{tab:sim-valid}",
 "\\begin{tabular}{llrrrrrr}", "\\toprule",
 "Design & Transition(time) & Bias & MCSE & ESE & ASE & CP & MCSE \\\\", "\\midrule")
q <- subset(P, scenario %in% c("S1e_rho50_n2000", "S2_ufree_n2000") & method == "IV")
q <- q[order(match(q$curve, c("B01", "B02", "B12")), q$time, q$design), ]
for (i in seq_len(nrow(q))) tex <- c(tex, sprintf("%s & %s(%s) & %s & %s & %s & %s & %s & %s \\\\",
  q$design[i], q$curve[i], q$time[i], fmt(q$bias[i]), fmt(q$MCSE_bias[i]), fmt(q$ESE[i]),
  fmt(q$ASE[i]), fmt(q$CP[i]), fmt(q$MCSE_CP[i])))
tex <- c(tex, "\\bottomrule", "\\end{tabular}", "\\end{table}", "",
 "\\begin{table}[htbp]", "\\centering",
 "\\caption{Entry-balance violations; bias and coverage against $0.12s$. Limit: bias of the probability limit.}",
 "\\label{tab:sim-viol}", "\\begin{tabular}{llrrrrr}", "\\toprule",
 "Design & $s$ & Bias & MCSE & ESE & CP & Limit \\\\", "\\midrule")
q2 <- subset(P, scenario %in% c("S3a_viol_n2000", "S3b_viol_n4000", "S4a_onset_n2000", "S4b_onset_n4000") &
               method == "IV" & curve == "B12")
q2 <- q2[order(q2$design, q2$n, q2$time), ]
for (i in seq_len(nrow(q2))) {
  lim <- subset(L, design == q2$design[i] & abs(s - q2$time[i]) < 1e-8)$bias_limit[1]
  tex <- c(tex, sprintf("%s, $n=%d$ & %s & %s & %s & %s & %s & %s \\\\", q2$design[i], q2$n[i], q2$time[i],
    fmt(q2$bias[i]), fmt(q2$MCSE_bias[i]), fmt(q2$ESE[i]), fmt(q2$CP[i]), fmt(lim)))
}
tex <- c(tex, "\\bottomrule", "\\end{tabular}", "\\end{table}", "",
 "\\begin{table}[htbp]", "\\centering", "\\caption{Bootstrap standard-error check for $B_{12}$.}",
 "\\label{tab:sim-bootstrap}", "\\begin{tabular}{lrrrrr}", "\\toprule",
 "$s$ & ESE & IF ASE & Bootstrap ASE & IF coverage & Bootstrap coverage \\\\", "\\midrule")
for (i in 1:3) tex <- c(tex, sprintf("%s & %s & %s & %s & %s & %s \\\\", c("0.5", "1.0", "1.5")[i],
  fmt(B$ESE[i]), fmt(B$IF_ASE[i]), fmt(B$Boot_ASE[i]), fmt(B$CP_IF[i]), fmt(B$CP_Boot[i])))
tex <- c(tex, "\\bottomrule", "\\end{tabular}", "\\end{table}")
writeLines(tex, file.path("output", "simulation_results.tex"))

pick <- subset(P, method == "IV" & curve == "B12" & scenario %in% c("S1e_rho50_n2000", "S3a_viol_n2000", "S4a_onset_n2000"))
pick <- pick[order(pick$design, pick$time), ]
pdf(file.path("output", "simulation_B12.pdf"), width = 6.6, height = 4.4, useDingbats = FALSE)
ylim <- range(c(0, pick$truth, pick$truth + pick$bias - pick$ESE, pick$truth + pick$bias + pick$ESE))
plot(NA, xlim = range(pick$time), ylim = ylim, xlab = "Gap time s", ylab = expression(B[12](s)), xaxt = "n")
axis(1, at = sort(unique(pick$time)))
cols <- c(A = "#1b9e77", C = "#d95f02", D = "#7570b3"); pch <- c(A = 16, C = 17, D = 15)
for (d in c("A", "C", "D")) { z <- pick[pick$design == d, ]; mu <- z$truth + z$bias
  arrows(z$time, mu - z$ESE, z$time, mu + z$ESE, angle = 90, code = 3, length = .04, col = cols[d])
  lines(z$time, mu, type = "b", pch = pch[d], col = cols[d], lwd = 1.2) }
z <- pick[pick$design == "A", ]; lines(z$time, z$truth, col = "black", lty = 2, lwd = 1.2)
legend("topleft", legend = c("A: valid", "C: balance violation", "D: onset selection", "target"),
       col = c(cols, "black"), pch = c(pch, NA), lty = c(1, 1, 1, 2), bty = "n", cex = .78)
invisible(dev.off())
message("Wrote output/simulation_results.tex and output/simulation_B12.pdf")
